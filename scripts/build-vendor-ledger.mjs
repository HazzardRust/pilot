#!/usr/bin/env node
/**
 * Assembles `VENDOR.md` — the one re-sync ledger L8 asks for — from the fragments
 * under `vendor/`.
 *
 * Two slices vendor in parallel, so each owns its own fragment: `vendor/methodology.md`
 * for the methodology skills and `vendor/toolbox.md` for the toolbox. That is what keeps
 * them from editing one file at once, and it leaves a reader with no single place to look.
 * This script is that place. It is generated rather than written because a hand-kept
 * third copy of a hundred and fifty rows is a copy that goes stale, and `--check` is what
 * makes staleness a failing test rather than a discovery six months later.
 *
 * Where each section's upstream comes from is deliberate: the provenance headers of the
 * files the fragment lists, never the fragment's own prose. `check-provenance.mjs`
 * already enforces the headers against the rows in both directions, so the headers are
 * the enforced source of truth and the prose is not; and rows inside one fragment that
 * disagree about their upstream are a mistake worth refusing rather than averaging.
 *
 * Usage:
 *   node build-vendor-ledger.mjs            write VENDOR.md
 *   node build-vendor-ledger.mjs --check    fail if VENDOR.md is not what this produces
 */

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

// The heading and the directory come from the script that parses the rows, for the
// same reason the header pattern does: a second copy is a copy that can disagree.
import { parseHeader, parseLedger, LEDGER_HEADING, LEDGER_DIR } from './check-provenance.mjs';

/** The assembled ledger, at the repository root where a reader looks for it. */
export const LEDGER_FILE = 'VENDOR.md';

/** Where the fragments live; slice 7 owns one, slice 8 the other. */
const FRAGMENT_DIR = LEDGER_DIR;

const GENERATED_BY = 'scripts/build-vendor-ledger.mjs';

/** The fragments, in a stable order so the output does not depend on the filesystem. */
function ledgerFragments(root) {
  const dir = path.join(root, FRAGMENT_DIR);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((name) => name.endsWith('.md'))
    .sort()
    .map((name) => `${FRAGMENT_DIR}/${name}`);
}

/** The table under `## Vendored files`, as it stands in the fragment. */
function rowsTable(source) {
  const lines = [];
  let inFiles = false;
  for (const line of source.split('\n')) {
    if (line.startsWith('## ')) inFiles = LEDGER_HEADING.test(line);
    if (inFiles && line.trim().startsWith('|')) lines.push(line.trimEnd());
  }
  return lines;
}

const titleOf = (source, fallback) => {
  const heading = /^#\s+(.+?)\s*$/m.exec(source);
  return heading ? heading[1] : fallback;
};

/** The project, version, copyright and licence every file in this fragment agrees on. */
function upstreamOf(root, fragment, files) {
  const seen = new Map();
  for (const file of files) {
    const full = path.join(root, file);
    if (!fs.existsSync(full)) throw new Error(`${fragment} lists ${file}, which does not exist`);
    const fields = parseHeader(fs.readFileSync(full, 'utf8'));
    if (!fields) throw new Error(`${file} is listed in ${fragment} but has no provenance header`);

    const project = fields.upstream.split(' - ')[0].trim();
    const licence = (fields.licence || '').split(' - ')[0].trim();
    const key = JSON.stringify([project, fields.copyright, licence]);
    if (!seen.has(key)) seen.set(key, { project, copyright: fields.copyright, licence, file });
  }

  if (seen.size === 0) throw new Error(`${fragment} lists no files`);
  if (seen.size > 1) {
    const named = [...seen.values()].map((one) => `${one.project} (${one.file})`);
    throw new Error(
      `${fragment} mixes upstreams: ${named.join(' and ')}. One fragment is one upstream; ` +
        'split it, or fix the provenance header that is wrong.',
    );
  }
  return seen.values().next().value;
}

/** Each fragment as `{ fragment, title, project, copyright, licence, count, table }`. */
function ledgerSections(root) {
  return ledgerFragments(root).map((fragment) => {
    const source = fs.readFileSync(path.join(root, fragment), 'utf8');
    const files = [...parseLedger(source).keys()];
    return {
      fragment,
      title: titleOf(source, fragment),
      count: files.length,
      table: rowsTable(source),
      ...upstreamOf(root, fragment, files),
    };
  });
}

const PREAMBLE = [
  '# Vendoring ledger',
  '',
  `<!-- Generated by \`${GENERATED_BY}\` from the fragments under \`vendor/\`.`,
  '     Do not edit this file: edit the fragment a row lives in and run the script again.',
  `     \`node ${GENERATED_BY} --check\` fails when this file and the fragments disagree. -->`,
  '',
  'Pilot is by HazzardRust and is MIT-licensed; `LICENSE` is its notice. Some of what it',
  'ships was copied from three MIT-licensed upstream projects rather than depended on',
  '(ADR 0003), and this file is the map for staying current with them: every file taken,',
  'where it came from, and what this project changed.',
  '',
  'The full licence text of every upstream travels in `THIRD-PARTY-NOTICES.md`. ADR 0011',
  "keeps their names out of every path, so a file's provenance header and its row here are",
  'the only traces of where it came from: `scripts/check-provenance.mjs` enforces those two',
  'against each other in both directions, and `scripts/check-upstream.mjs` reports which of',
  'them have drifted from the upstream installed on this machine.',
  '',
];

export function buildLedger(root) {
  const sections = ledgerSections(root);

  const summary = [
    '| Upstream | Licence | Files | Fragment |',
    '| --- | --- | --- | --- |',
    ...sections.map(
      ({ project, licence, copyright, count, fragment }) =>
        `| ${project} | ${licence}, ${copyright} | ${count} | [\`${fragment}\`](${fragment}) |`,
    ),
    '',
  ];

  const bodies = sections.flatMap(
    ({ title, project, copyright, licence, count, fragment, table }) => [
      `## ${title}`,
      '',
      `${count} file(s) from **${project}**, ${licence}, ${copyright}.`,
      `[\`${fragment}\`](${fragment}) carries the rest: the header format, what was deliberately`,
      'not taken, and how to re-sync.',
      '',
      ...table,
      '',
    ],
  );

  return [...PREAMBLE, ...summary, ...bodies].join('\n').replace(/\n+$/, '\n');
}

/** Whether the ledger on disk is what the fragments say it should be. */
export function checkLedger(root, outPath) {
  const target = outPath || path.join(root, LEDGER_FILE);
  const wanted = buildLedger(root);

  if (!fs.existsSync(target)) {
    return {
      ok: false,
      reason: `${target} does not exist; run \`node ${GENERATED_BY}\` to write it.`,
    };
  }

  const current = fs.readFileSync(target, 'utf8');
  if (current === wanted) return { ok: true, reason: `${target} is current.` };

  const currentLines = current.split('\n');
  const wantedLines = wanted.split('\n');
  const at = wantedLines.findIndex((line, i) => line !== currentLines[i]);
  return {
    ok: false,
    reason:
      `${target} is not what the fragments under vendor/ say it should be ` +
      `(first difference at line ${at + 1}). Run \`node ${GENERATED_BY}\` to regenerate it.`,
  };
}

const USAGE = [
  `Usage: node ${GENERATED_BY} [--check]`,
  '',
  `  (no argument)  write ${LEDGER_FILE} from the fragments under vendor/`,
  `  --check        exit 1 if ${LEDGER_FILE} is not what those fragments produce`,
].join('\n');

function main(argv) {
  const root = process.cwd();

  if (argv.includes('--help') || argv.includes('-h')) {
    console.log(USAGE);
    return;
  }
  const unknown = argv.filter((arg) => arg !== '--check');
  if (unknown.length) {
    console.error(`Unknown argument ${unknown[0]}.\n${USAGE}`);
    process.exitCode = 2;
    return;
  }

  try {
    if (argv.includes('--check')) {
      const { ok, reason } = checkLedger(root);
      console[ok ? 'log' : 'error'](reason);
      if (!ok) process.exitCode = 1;
      return;
    }

    const target = path.join(root, LEDGER_FILE);
    const before = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    const wanted = buildLedger(root);
    if (before === wanted) {
      console.log(`${LEDGER_FILE} is already current.`);
      return;
    }
    fs.writeFileSync(target, wanted, 'utf8');
    console.log(`Wrote ${LEDGER_FILE} from ${ledgerFragments(root).join(', ')}.`);
  } catch (err) {
    console.error(err.message);
    process.exitCode = 1;
  }
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  main(process.argv.slice(2));
}
