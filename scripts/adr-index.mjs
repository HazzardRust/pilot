#!/usr/bin/env node
/**
 * Writes or checks `docs/adr/README.md`, the index of every ADR: one table row
 * per `NNNN-slug.md` file, by number, with its title, status and the first
 * sentence of its body. The index is generated, never hand-written; the test
 * `scripts/test/adr-index.test.mjs` runs the check over the real directory, so
 * an ADR added without regenerating fails `npm test`.
 *
 *   node scripts/adr-index.mjs [--dir docs/adr] [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ADR_FILE = /^(\d{4})-.+\.md$/;
const INDEX = 'README.md';
const SENTENCE_MAX = 160;
const KEYS = ['status', 'date', 'tags', 'supersedes', 'superseded_by', 'paths'];
const STATUSES = ['proposed', 'accepted', 'superseded', 'amended', 'deprecated'];
/** The line that marks an index as generated: only such an index is ever regenerated (clean-landing L2). */
export const GENERATED_HEADER = 'Generated by `npm run adr-index` from the ADRs in this directory; do not edit by hand.';
const HEADER = [
  '# Architecture decision records',
  '',
  GENERATED_HEADER,
  '',
  '| # | Decision | Status | Summary |',
  '| --- | --- | --- | --- |',
];

const cell = (text) => text.replace(/\|/g, '\\|');
const readLf = (file) => fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');

function frontMatter(lines) {
  const end = lines[0] === '---' ? lines.indexOf('---', 1) : -1;
  if (end === -1) return { fields: null, rest: lines };
  const fields = {};
  for (const line of lines.slice(1, end)) {
    const m = /^(\w+):\s*(.*)$/.exec(line);
    if (m) fields[m[1]] = m[2].trim();
  }
  return { fields, rest: lines.slice(end + 1) };
}

/** Blank-line separated paragraphs, each joined onto one line. */
function paragraphs(lines) {
  const out = [];
  let current = [];
  for (const line of [...lines, '']) {
    if (line.trim() !== '') current.push(line.trim());
    else if (current.length) {
      out.push(current.join(' '));
      current = [];
    }
  }
  return out;
}

function firstSentence(paragraph) {
  const sentence = /^.*?[.!?](?=\s|$)/.exec(paragraph)?.[0] ?? paragraph;
  return sentence.length > SENTENCE_MAX ? `${sentence.slice(0, SENTENCE_MAX - 3)}...` : sentence;
}

const parse = (dir, file) => frontMatter(readLf(path.join(dir, file)).split('\n'));

/** `[0001, 0002]` as `['0001', '0002']`; `[]` as none. */
const list = (value) =>
  value
    .replace(/^\[|\]$/g, '')
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean);

function row(dir, file) {
  const number = ADR_FILE.exec(file)[1];
  const { fields, rest } = parse(dir, file);
  const titleAt = rest.findIndex((line) => line.startsWith('# '));
  const title = titleAt === -1 ? file : rest[titleAt].slice(2).trim();
  const body = paragraphs(rest.slice(titleAt + 1));
  const status = fields?.status ?? '';
  const summary = firstSentence(body[0] ?? '');
  return `| ${number} | [${cell(title)}](${file}) | ${cell(status)} | ${cell(summary)} |`;
}

const adrFiles = (dir) => fs.readdirSync(dir).filter((f) => ADR_FILE.test(f)).sort();

/** The number a run's own, not yet allocated ADR carries on a feature branch; never indexed. */
export const PLACEHOLDER = 'NNNN';

/** One past the highest numbered ADR file in `dir`, four digits. */
export function nextNumber(dir) {
  const highest = Math.max(0, ...adrFiles(dir).map((f) => Number(f.slice(0, 4))));
  return String(highest + 1).padStart(4, '0');
}

/** One table row per ADR file in `dir`, by number. */
export function indexLines(dir) {
  return adrFiles(dir).map((file) => row(dir, file));
}

/** The whole generated index of the ADRs in `dir`. */
export const renderIndex = (dir) => `${[...HEADER, ...indexLines(dir)].join('\n')}\n`;

/** Each ADR's front matter has every key and an allowed status, and supersession is named on both sides. */
function frontMatterProblems(dir) {
  const problems = [];
  const links = new Map();
  for (const file of adrFiles(dir)) {
    const number = file.slice(0, 4);
    const { fields } = parse(dir, file);
    if (fields === null) {
      problems.push(`${number} has no front matter`);
      continue;
    }
    for (const key of KEYS.filter((k) => !(k in fields))) problems.push(`${number} has no ${key} in its front matter`);
    if ('status' in fields && !STATUSES.includes(fields.status)) {
      problems.push(`${number} has status "${fields.status}", not one of ${STATUSES.join(', ')}`);
    }
    links.set(number, { supersedes: list(fields.supersedes ?? ''), by: list(fields.superseded_by ?? '') });
  }
  const placeholder = fs.readdirSync(dir).some((f) => f.startsWith(`${PLACEHOLDER}-`) && f.endsWith('.md'));
  for (const [number, { supersedes, by }] of links) {
    for (const old of supersedes) {
      if (!links.get(old)?.by.includes(number)) {
        problems.push(`${number} supersedes ${old} but ${old} has no superseded_by ${number}`);
      }
    }
    for (const newer of by) {
      if (placeholder && newer === PLACEHOLDER) continue;
      if (!links.get(newer)?.supersedes.includes(number)) {
        problems.push(`${number} is superseded_by ${newer} but ${newer} has no supersedes ${number}`);
      }
    }
  }
  return problems;
}

/**
 * Compares `dir/README.md` with what would be generated, naming each stale or missing row,
 * and checks every ADR's front matter.
 */
export function checkIndex(dir) {
  const indexPath = path.join(dir, INDEX);
  if (!fs.existsSync(indexPath)) {
    return { ok: false, problems: [`${indexPath} is missing; run \`npm run adr-index\``] };
  }
  const text = readLf(indexPath);
  const written = new Map();
  for (const line of text.split('\n')) {
    const m = /^\| (\d{4}) \|/.exec(line);
    if (m) written.set(m[1], line);
  }
  const problems = [];
  const owners = new Map();
  const dupes = new Set();
  for (const file of adrFiles(dir)) {
    const number = file.slice(0, 4);
    if (owners.has(number)) {
      problems.push(`ADR ${number} is used by ${owners.get(number)} and ${file}`);
      dupes.add(number);
    } else owners.set(number, file);
  }
  for (const [number, file] of owners) {
    const have = written.get(number);
    written.delete(number);
    if (dupes.has(number)) continue;
    if (have === undefined) problems.push(`${file} is missing from the index`);
    else if (have !== row(dir, file)) problems.push(`the row for ${file} is stale`);
  }
  for (const number of written.keys()) problems.push(`the index lists ${number}, which has no ADR file`);
  if (problems.length === 0 && text !== renderIndex(dir)) problems.push(`${indexPath} differs from the generated index`);
  problems.push(...frontMatterProblems(dir));
  return { ok: problems.length === 0, problems };
}

function main(argv) {
  const at = argv.indexOf('--dir');
  const dir = at === -1 ? path.join('docs', 'adr') : argv[at + 1];
  const unknown = argv.filter((a, i) => a !== '--check' && a !== '--dir' && i !== at + 1);
  if (!dir || dir.startsWith('--') || (at !== -1 ? unknown : argv.filter((a) => a !== '--check')).length) {
    console.error('usage: node scripts/adr-index.mjs [--dir docs/adr] [--check]');
    process.exit(2);
  }
  if (argv.includes('--check')) {
    const { ok, problems } = checkIndex(dir);
    for (const p of problems) console.error(p);
    if (!ok) process.exit(1);
    console.log(`${path.join(dir, INDEX)} is current`);
    return;
  }
  fs.writeFileSync(path.join(dir, INDEX), renderIndex(dir), 'utf8');
  console.log(`wrote ${path.join(dir, INDEX)} (${adrFiles(dir).length} ADRs)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2));
}
